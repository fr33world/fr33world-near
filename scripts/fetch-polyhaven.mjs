#!/usr/bin/env node
/**
 * Downloads the Poly Haven (CC0) textures the client uses, re-encodes them to 1K WebP with
 * ffmpeg, and rewrites the Poly Haven section of assets/registry.yaml.
 *
 *   node scripts/fetch-polyhaven.mjs [--force]
 * Textures already present are kept (their registry entries are still written); --force
 * downloads and re-encodes everything.
 *
 * Every entry names its source page; the license snapshot is assets/licenses/polyhaven-license.txt.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const outDir = join(root, 'apps/client/public/assets/textures');
const tmp = join(root, '.raw/polyhaven');
mkdirSync(outDir, { recursive: true });
mkdirSync(tmp, { recursive: true });

/** name in the game → Poly Haven id. Maps: colour, OpenGL normal, roughness. */
const TEXTURES = {
  road: 'asphalt_02',
  sidewalk: 'concrete_pavement_02',
  grass: 'leafy_grass',
  stucco: 'white_stucco',
  facade_tiles: 'rectangular_facade_tiles',
  brick: 'brick_wall_09',
  cladding: 'exterior_wall_cladding',
  palm_bark: 'palm_tree_bark',
  // Residential roofs: terracotta barrel tiles (Spanish style, LA's classic) and shingles.
  roof_clay: 'clay_roof_tiles_02',
  roof_shingle: 'grey_roof_01',
  // The hills (owner, 2026-10-29: real hillside, not smooth green): rocky grassland on the
  // slopes, bare rock on the steepest, forest floor under the scrub.
  hill_ground: 'rocky_terrain_02',
  hill_rock: 'aerial_rocks_02',
  hill_dirt: 'forest_ground_04',
};
const force = process.argv.includes('--force');
const MAPS = { color: 'Diffuse', normal: 'nor_gl', rough: 'Rough' };

const today = new Date().toISOString().slice(0, 10);
const entries = [];

for (const [name, id] of Object.entries(TEXTURES)) {
  const files = await (await fetch(`https://api.polyhaven.com/files/${id}`)).json();
  const info = await (await fetch(`https://api.polyhaven.com/info/${id}`)).json();
  const authors = Object.keys(info.authors ?? {}).join(', ');
  for (const [suffix, key] of Object.entries(MAPS)) {
    const out = join(outDir, `${name}_${suffix}.webp`);
    const entry = {
      id: `${name}_${suffix}`,
      file: `textures/${name}_${suffix}.webp`,
      source_url: `https://polyhaven.com/a/${id}`,
      source_name: `Poly Haven (${info.name ?? id}, ${key} 1K)`,
      author: authors,
    };
    if (existsSync(out) && !force) {
      entries.push(entry);
      continue;
    }
    const url = files[key]?.['1k']?.jpg?.url;
    if (!url) throw new Error(`${id} has no 1k ${key}`);
    const jpg = join(tmp, `${id}_${suffix}.jpg`);
    writeFileSync(jpg, Buffer.from(await (await fetch(url)).arrayBuffer()));
    const quality = suffix === 'normal' ? '92' : '80';
    execFileSync('ffmpeg', [
      '-loglevel',
      'error',
      '-y',
      '-i',
      jpg,
      '-c:v',
      'libwebp',
      '-quality',
      quality,
      out,
    ]);
    rmSync(jpg);
    entries.push(entry);
  }
  console.log(`${name} ← ${id}`);
}

// Rewrite only the generated Poly Haven section of the registry.
const registryPath = join(root, 'assets/registry.yaml');
const begin = '# BEGIN polyhaven (generated by scripts/fetch-polyhaven.mjs)';
const end = '# END polyhaven';
let registry = readFileSync(registryPath, 'utf8');
const section = [
  begin,
  ...entries.map((e) =>
    [
      `  - id: ${e.id}`,
      `    file: ${e.file}`,
      `    class: texture`,
      `    source_url: ${e.source_url}`,
      `    source_name: '${e.source_name.replace(/'/g, "''")}'`,
      `    author: '${e.author.replace(/'/g, "''")}'`,
      `    license: { name: CC0 1.0, url: 'https://polyhaven.com/license', verified_at: '${today}' }`,
      `    license_snapshot: polyhaven-license.txt`,
      `    notes: 1K JPG re-encoded to WebP.`,
    ].join('\n'),
  ),
  end,
].join('\n');
const from = registry.indexOf(begin);
const to = registry.indexOf(end);
registry =
  from >= 0 && to > from
    ? registry.slice(0, from) + section + registry.slice(to + end.length)
    : `${registry.trimEnd()}\n${section}\n`;
writeFileSync(registryPath, registry);
console.log(`${entries.length} files, registry updated`);
