#!/usr/bin/env node
/**
 * Downloads the Poly Haven (CC0) street props the client places (city/props.ts), cuts each to
 * a phone's triangle budget, shrinks its textures to 256² WebP, compresses the geometry
 * (meshopt), and rewrites the props section of assets/registry.yaml.
 *
 *   node scripts/assets/fetch-props.mjs [--force]
 *
 * Models already present are kept (their registry entries are still written). Every entry
 * names its source page; the license snapshot is assets/licenses/polyhaven-license.txt.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { dedup, meshopt, prune, simplify, textureCompress, weld } from '@gltf-transform/functions';
import { MeshoptDecoder, MeshoptEncoder, MeshoptSimplifier } from 'meshoptimizer';
import sharp from 'sharp';

const root = new URL('../..', import.meta.url).pathname;
const outDir = join(root, 'apps/client/public/assets/props');
const tmp = join(root, '.raw/props');
mkdirSync(outDir, { recursive: true });

/**
 * name in the game → Poly Haven id, the most triangles it may keep, and the meshes to drop
 * (some files hold a clean and a weathered copy side by side: the clean one is kept).
 */
const PROPS = {
  hydrant: { id: 'fire_hydrant', triangles: 1200, drop: /aged/ },
  bin: { id: 'metal_trash_can', triangles: 900, drop: /rust/ },
  bench: { id: 'painted_wooden_bench', triangles: 700 },
  planter: { id: 'planter_box_01', triangles: 1200 },
  barrier: { id: 'concrete_road_barrier_02', triangles: 500 },
  // Inside the public buildings (interiors).
  plant: { id: 'potted_plant_01', triangles: 1800 },
  sofa: { id: 'Sofa_01', triangles: 1600 },
  desk: { id: 'metal_office_desk', triangles: 900 },
};
const TEXTURE = 256;
const force = process.argv.includes('--force');
const today = new Date().toISOString().slice(0, 10);

await Promise.all([MeshoptDecoder.ready, MeshoptEncoder.ready, MeshoptSimplifier.ready]);
const io = new NodeIO()
  .registerExtensions(ALL_EXTENSIONS)
  .registerDependencies({ 'meshopt.decoder': MeshoptDecoder, 'meshopt.encoder': MeshoptEncoder });

const triangles = (doc) =>
  doc
    .getRoot()
    .listMeshes()
    .flatMap((m) => m.listPrimitives())
    .reduce(
      (n, p) => n + (p.getIndices()?.getCount() ?? p.getAttribute('POSITION').getCount()) / 3,
      0,
    );

const entries = [];
for (const [name, { id, triangles: budget, drop }] of Object.entries(PROPS)) {
  const info = await (await fetch(`https://api.polyhaven.com/info/${id}`)).json();
  const entry = {
    id: `prop_${name}`,
    file: `props/${name}.glb`,
    source_url: `https://polyhaven.com/a/${id}`,
    source_name: `Poly Haven (${info.name ?? id}, glTF 1K)`,
    author: Object.keys(info.authors ?? {}).join(', '),
    budget,
  };
  entries.push(entry);
  const out = join(outDir, `${name}.glb`);
  if (existsSync(out) && !force) continue;

  // The glTF and everything it includes (buffers, textures), kept in .raw for re-runs.
  const files = await (await fetch(`https://api.polyhaven.com/files/${id}`)).json();
  const gltf = files.gltf['1k'].gltf;
  const dir = join(tmp, id);
  const main = join(dir, `${id}.gltf`);
  if (!existsSync(main) || force) {
    mkdirSync(dir, { recursive: true });
    writeFileSync(main, Buffer.from(await (await fetch(gltf.url)).arrayBuffer()));
    for (const [path, file] of Object.entries(gltf.include ?? {})) {
      const target = join(dir, path);
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, Buffer.from(await (await fetch(file.url)).arrayBuffer()));
    }
  }

  const doc = await io.read(main);
  for (const node of doc.getRoot().listNodes()) if (drop?.test(node.getName())) node.dispose();
  await doc.transform(prune());
  const before = triangles(doc);
  const nodes = doc
    .getRoot()
    .listNodes()
    .filter((n) => n.getMesh())
    .map((n) => n.getName());
  await doc.transform(
    dedup(),
    weld(),
    simplify({ simplifier: MeshoptSimplifier, ratio: Math.min(1, budget / before), error: 0.04 }),
    textureCompress({ encoder: sharp, targetFormat: 'webp', resize: [TEXTURE, TEXTURE] }),
    prune(),
    meshopt({ encoder: MeshoptEncoder, level: 'medium' }),
  );
  await io.write(out, doc);
  console.log(
    `${name} ← ${id}: ${Math.round(before)} → ${Math.round(triangles(doc))} triangles; meshes ${nodes.join(', ')}`,
  );
}

// Rewrite only the generated props section of the registry.
const registryPath = join(root, 'assets/registry.yaml');
const begin = '# BEGIN polyhaven-props (generated by scripts/assets/fetch-props.mjs)';
const end = '# END polyhaven-props';
let registry = readFileSync(registryPath, 'utf8');
const section = [
  begin,
  ...entries.map((e) =>
    [
      `  - id: ${e.id}`,
      `    file: ${e.file}`,
      '    class: model',
      `    source_url: ${e.source_url}`,
      `    source_name: '${e.source_name}'`,
      `    author: '${e.author}'`,
      `    license: { name: CC0 1.0, url: 'https://polyhaven.com/license', verified_at: '${today}' }`,
      '    license_snapshot: polyhaven-license.txt',
      `    notes: Simplified to at most ${e.budget} triangles, textures 256² WebP, meshopt geometry.`,
    ].join('\n'),
  ),
  `  ${end}`,
].join('\n');
const at = registry.indexOf(begin);
if (at >= 0) {
  const stop = registry.indexOf(end, at) + end.length;
  registry = registry.slice(0, at) + section.trimStart() + registry.slice(stop);
} else {
  registry = `${registry.trimEnd()}\n  ${section.trimStart()}\n`;
}
writeFileSync(registryPath, registry);
